import type { Command } from "commander";
import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative, resolve } from "node:path";
import { stringify } from "yaml";
import { SkillEvalSpecSchema } from "@j-rig/core";
import { loadSkillEvalSpec, loadSkillMd } from "../lib/loaders.js";
import { buildBaselineSpec } from "./scaffold-spec.js";

const IGNORED_DIRECTORIES = new Set([
  ".git",
  ".j-rig",
  "node_modules",
  "dist",
  "build",
  "coverage",
]);

const BATCH_ID_RE = /^[A-Za-z0-9][A-Za-z0-9._:-]*$/;

export interface EvalBatchOptions {
  skillsRoot: string;
  provider?: string;
  models?: string;
  judgeProvider?: string;
  judgeModel?: string;
  samples?: number;
  db: string;
  outputDir?: string;
  batchId?: string;
  writeSpecs?: boolean;
  continueOnError?: boolean;
  trigger?: boolean;
  functional?: boolean;
  baselineCheck?: boolean;
  runSelfTest?: boolean;
  traceBoundary?: boolean;
  json?: boolean;
  /** Test seam; production uses the built CLI entrypoint in this process. */
  invokeEval?: EvalInvoker;
}

export interface EvalInvocationResult {
  exitCode: number | null;
  signal: NodeJS.Signals | null;
  stdout: string;
  stderr: string;
}

export type EvalInvoker = (
  args: string[],
  options: { cwd: string; env: NodeJS.ProcessEnv },
) => Promise<EvalInvocationResult>;

export interface EvalBatchEntry {
  skill_dir: string;
  skill_relative_path: string;
  skill_name: string;
  spec_path: string;
  spec_source: "existing" | "generated";
  bundle_path: string;
  result_path: string;
  status: "completed" | "failed";
  exit_code: number | null;
  signal: NodeJS.Signals | null;
  duration_ms: number;
  models: Array<{
    model: string;
    provider?: string;
    decision?: string;
    ground_truth?: boolean;
  }>;
  diagnostics?: string;
  error?: string;
}

export interface EvalBatchManifest {
  schema: "j-rig/eval-batch/v1";
  batch_id: string;
  skills_root: string;
  provider: string;
  models: string | null;
  database: string;
  generated_at: string;
  completed_at: string;
  summary: {
    discovered: number;
    completed: number;
    failed: number;
  };
  entries: EvalBatchEntry[];
}

interface DiscoveredSkill {
  directory: string;
  relativePath: string;
  slug: string;
}

interface PreparedSpec {
  path: string;
  source: "existing" | "generated";
}

function findExistingSpec(directory: string): string | undefined {
  return ["eval-spec.yaml", "eval-spec.yml"].map((name) => join(directory, name)).find(existsSync);
}

function discoverSkillDirectories(root: string): DiscoveredSkill[] {
  const discovered: string[] = [];
  const pending = [root];

  while (pending.length > 0) {
    const directory = pending.pop();
    if (!directory) continue;

    if (existsSync(join(directory, "SKILL.md"))) {
      discovered.push(directory);
      // A skill directory is a leaf for this batch. Nested fixtures or bundled
      // examples must not become accidental second skills.
      continue;
    }

    const children = readdirSync(directory, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && !IGNORED_DIRECTORIES.has(entry.name))
      .map((entry) => entry.name)
      .sort()
      .reverse();
    for (const child of children) pending.push(join(directory, child));
  }

  return discovered.sort().map((directory, index) => {
    const relativePath = relative(root, directory) || basename(directory);
    const digest = createHash("sha256").update(relativePath).digest("hex").slice(0, 10);
    const safePath = relativePath.replaceAll(/[\\/]+/g, "--").replaceAll(/[^A-Za-z0-9._-]/g, "-");
    return {
      directory,
      relativePath,
      slug: `${String(index + 1).padStart(3, "0")}-${safePath}-${digest}`,
    };
  });
}

function validateBatchId(batchId: string): string {
  if (!BATCH_ID_RE.test(batchId)) {
    throw new Error(
      `batchId must contain only letters, numbers, dots, underscores, colons, or hyphens (got "${batchId}")`,
    );
  }
  return batchId;
}

function makeBatchId(root: string, requested?: string): string {
  if (requested) return validateBatchId(requested);
  const timestamp = new Date()
    .toISOString()
    .replaceAll(/[^0-9]/g, "")
    .slice(0, 14);
  const digest = createHash("sha256").update(root).digest("hex").slice(0, 10);
  return `batch-${timestamp}-${digest}`;
}

function generatedSpecHeader(skillName: string): string {
  return (
    `# Generated by j-rig eval-batch for "${skillName}".\n` +
    "# This is a baseline spec: trigger engagement, output presence, and prompt-leakage safety.\n" +
    "# Add hand-authored functional criteria before treating this as deep skill evidence.\n"
  );
}

function prepareSpec(skill: DiscoveredSkill, outputDir: string, writeSpecs: boolean): PreparedSpec {
  const existing = findExistingSpec(skill.directory);
  if (existing) {
    loadSkillEvalSpec(existing, skill.directory);
    return { path: existing, source: "existing" };
  }

  const { parsed } = loadSkillMd(skill.directory);
  const rawName = typeof parsed.frontmatter.name === "string" ? parsed.frontmatter.name : "";
  const rawDescription =
    typeof parsed.frontmatter.description === "string" ? parsed.frontmatter.description : "";
  const skillName = rawName || basename(skill.directory);
  const description = rawDescription.trim() || `the ${skillName} skill`;
  const generated = buildBaselineSpec(skillName, description);
  const validated = SkillEvalSpecSchema.safeParse(generated);
  if (!validated.success) {
    const details = validated.error.issues
      .map((issue) => `${issue.path.join(".")}: ${issue.message}`)
      .join("; ");
    throw new Error(`Generated baseline spec for ${skill.relativePath} is invalid: ${details}`);
  }

  const target = writeSpecs
    ? join(skill.directory, "eval-spec.yaml")
    : join(outputDir, "specs", skill.slug, "eval-spec.yaml");
  mkdirSync(dirname(target), { recursive: true });
  if (!existsSync(target)) {
    writeFileSync(
      target,
      generatedSpecHeader(validated.data.skill_name) + stringify(validated.data),
    );
  }
  loadSkillEvalSpec(target, skill.directory);
  return { path: target, source: "generated" };
}

function parseEvalModels(stdout: string): EvalBatchEntry["models"] {
  try {
    const parsed = JSON.parse(stdout) as Record<string, unknown>;
    return Object.entries(parsed).flatMap(([model, value]) => {
      if (!value || typeof value !== "object") return [];
      const row = value as {
        provider?: unknown;
        ground_truth?: unknown;
        decision?: unknown;
        report?: { decision?: unknown };
      };
      return [
        {
          model,
          ...(typeof row.provider === "string" ? { provider: row.provider } : {}),
          ...(typeof row.decision === "string"
            ? { decision: row.decision }
            : typeof row.report?.decision === "string"
              ? { decision: row.report.decision }
              : {}),
          ...(typeof row.ground_truth === "boolean" ? { ground_truth: row.ground_truth } : {}),
        },
      ];
    });
  } catch {
    return [];
  }
}

function defaultEvalInvoker(
  args: string[],
  options: { cwd: string; env: NodeJS.ProcessEnv },
): Promise<EvalInvocationResult> {
  const configuredEntrypoint = process.env.JRIG_CLI_ENTRYPOINT?.trim() || process.argv[1];
  if (!configuredEntrypoint) {
    throw new Error("Unable to resolve the j-rig CLI entrypoint for eval-batch");
  }
  const entrypoint = resolve(configuredEntrypoint);

  return new Promise((resolveInvocation) => {
    let stdout = "";
    let stderr = "";
    let processError: string | undefined;
    const child = spawn(process.execPath, [entrypoint, ...args], {
      cwd: options.cwd,
      env: options.env,
      shell: false,
      stdio: ["ignore", "pipe", "pipe"],
    });
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk: string) => {
      stderr += chunk;
    });
    child.on("error", (error) => {
      processError = error.message;
    });
    child.on("close", (exitCode, signal) => {
      resolveInvocation({
        exitCode: processError ? 1 : exitCode,
        signal,
        stdout,
        stderr: processError ? `${stderr}${processError}` : stderr,
      });
    });
  });
}

function evalArgs(
  skillDir: string,
  specPath: string,
  options: EvalBatchOptions,
  dbPath: string,
  bundlePath: string,
): string[] {
  const args = [
    "eval",
    skillDir,
    "--spec",
    specPath,
    "--db",
    dbPath,
    "--emit-bundle",
    bundlePath,
    "--json",
  ];
  if (options.provider) args.push("--provider", options.provider);
  if (options.models) args.push("--models", options.models);
  if (options.judgeProvider) args.push("--judge-provider", options.judgeProvider);
  if (options.judgeModel) args.push("--judge-model", options.judgeModel);
  if (options.samples !== undefined) args.push("--samples", String(options.samples));
  if (options.trigger === false) args.push("--no-trigger");
  if (options.functional === false) args.push("--no-functional");
  if (options.baselineCheck) args.push("--baseline-check");
  if (options.runSelfTest) args.push("--run-self-test");
  if (options.traceBoundary) args.push("--trace-boundary");
  return args;
}

function writeManifest(path: string, manifest: EvalBatchManifest): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
}

/**
 * Scaffold missing specs and run every discovered skill through the existing
 * `j-rig eval` surface. Each child gets its own bundle path, while all runs
 * share the caller's SQLite evidence store. Child processes keep one broken
 * skill or malformed spec from corrupting or aborting the rest of the batch.
 */
export async function runEvalBatch(options: EvalBatchOptions): Promise<{
  manifest: EvalBatchManifest;
  manifestPath: string;
}> {
  const skillsRoot = resolve(options.skillsRoot);
  if (!existsSync(skillsRoot)) throw new Error(`Skills root not found: ${skillsRoot}`);
  const discovered = discoverSkillDirectories(skillsRoot);
  if (discovered.length === 0) throw new Error(`No SKILL.md files found under ${skillsRoot}`);

  const batchId = makeBatchId(skillsRoot, options.batchId);
  const outputDir = resolve(options.outputDir ?? join(".j-rig", "eval-batches", batchId));
  const dbPath = resolve(options.db);
  const bundleDir = join(outputDir, "bundles");
  const resultDir = join(outputDir, "results");
  const manifestPath = join(outputDir, "manifest.json");
  mkdirSync(bundleDir, { recursive: true });
  mkdirSync(resultDir, { recursive: true });

  const startedAt = new Date().toISOString();
  const entries: EvalBatchEntry[] = [];
  const invokeEval = options.invokeEval ?? defaultEvalInvoker;

  for (const skill of discovered) {
    const started = Date.now();
    const bundlePath = join(bundleDir, `${skill.slug}.json`);
    const resultPath = join(resultDir, `${skill.slug}.json`);
    let specPath = "";
    let specSource: EvalBatchEntry["spec_source"] = "generated";
    try {
      const spec = prepareSpec(skill, outputDir, options.writeSpecs === true);
      specPath = spec.path;
      specSource = spec.source;
      const invocation = await invokeEval(
        evalArgs(skill.directory, spec.path, options, dbPath, bundlePath),
        {
          cwd: skillsRoot,
          env: {
            ...process.env,
            JRIG_BATCH_ID: batchId,
            JRIG_BATCH_SKILL_RELATIVE_PATH: skill.relativePath,
            JRIG_BATCH_MANIFEST: manifestPath,
          },
        },
      );
      writeFileSync(resultPath, invocation.stdout, "utf8");
      const bundleMissing = invocation.exitCode === 0 && !existsSync(bundlePath);
      const completed = invocation.exitCode === 0 && !bundleMissing;
      const diagnostics = invocation.stderr.trim();
      entries.push({
        skill_dir: skill.directory,
        skill_relative_path: skill.relativePath,
        skill_name: loadSkillEvalSpec(spec.path, skill.directory).skill_name,
        spec_path: specPath,
        spec_source: specSource,
        bundle_path: bundlePath,
        result_path: resultPath,
        status: completed ? "completed" : "failed",
        exit_code: invocation.exitCode,
        signal: invocation.signal,
        duration_ms: Date.now() - started,
        models: parseEvalModels(invocation.stdout),
        ...(completed
          ? diagnostics.length > 0
            ? { diagnostics }
            : {}
          : {
              error:
                diagnostics ||
                (bundleMissing
                  ? "eval completed without writing an Evidence Bundle"
                  : `eval exited with ${
                      invocation.exitCode === null
                        ? `signal ${invocation.signal ?? "unknown"}`
                        : `code ${invocation.exitCode}`
                    }`),
            }),
      });
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      writeFileSync(resultPath, `${JSON.stringify({ error: message }, null, 2)}\n`, "utf8");
      entries.push({
        skill_dir: skill.directory,
        skill_relative_path: skill.relativePath,
        skill_name: basename(skill.directory),
        spec_path: specPath || findExistingSpec(skill.directory) || "",
        spec_source: specPath
          ? specSource
          : findExistingSpec(skill.directory)
            ? "existing"
            : "generated",
        bundle_path: bundlePath,
        result_path: resultPath,
        status: "failed",
        exit_code: null,
        signal: null,
        duration_ms: Date.now() - started,
        models: [],
        error: message,
      });
      if (options.continueOnError === false) break;
    }
  }

  const manifest: EvalBatchManifest = {
    schema: "j-rig/eval-batch/v1",
    batch_id: batchId,
    skills_root: skillsRoot,
    provider: options.provider ?? "auto",
    models: options.models ?? null,
    database: dbPath,
    generated_at: startedAt,
    completed_at: new Date().toISOString(),
    summary: {
      discovered: discovered.length,
      completed: entries.filter((entry) => entry.status === "completed").length,
      failed: entries.filter((entry) => entry.status === "failed").length,
    },
    entries,
  };
  writeManifest(manifestPath, manifest);
  return { manifest, manifestPath };
}

function printManifest(result: Awaited<ReturnType<typeof runEvalBatch>>, json?: boolean): void {
  if (json) {
    console.log(
      JSON.stringify({ ...result.manifest, manifest_path: result.manifestPath }, null, 2),
    );
    return;
  }
  console.log(`Eval batch ${result.manifest.batch_id}`);
  console.log(
    `  ${result.manifest.summary.completed}/${result.manifest.summary.discovered} completed; ` +
      `${result.manifest.summary.failed} failed`,
  );
  console.log(`  Manifest: ${result.manifestPath}`);
  for (const entry of result.manifest.entries) {
    console.log(`  ${entry.status === "completed" ? "✓" : "✗"} ${entry.skill_relative_path}`);
    if (entry.error) console.log(`    ${entry.error}`);
  }
}

/** Register `j-rig eval-batch`, the skills-root dogfood and evidence seam. */
export function registerEvalBatchCommand(program: Command): void {
  program
    .command("eval-batch")
    .description("Scaffold missing baseline specs and evaluate every SKILL.md under a skills root")
    .argument("<skills-root>", "Directory containing skill directories or one skill directory")
    .option("--provider <name>", "Provider forwarded to each eval invocation")
    .option("--models <list>", "Comma-separated models forwarded to each eval invocation")
    .option("--judge-provider <name>", "Independent judge provider forwarded to each eval")
    .option("--judge-model <id>", "Judge model forwarded to each eval")
    .option("--samples <n>", "Judge samples forwarded to each eval", (value: string) =>
      Number(value),
    )
    .option("--db <path>", "Shared SQLite evidence store", "j-rig.db")
    .option("--output-dir <path>", "Batch artifacts directory")
    .option("--batch-id <id>", "Stable lineage id for a rerun/resume")
    .option("--write-specs", "Write generated baseline specs beside source skills")
    .option(
      "--fail-fast",
      "Stop after the first invalid skill or failed evaluation (default: continue)",
    )
    .option("--no-trigger", "Skip trigger tests in each eval")
    .option("--no-functional", "Skip functional tests in each eval")
    .option("--baseline-check", "Run the opt-in baseline comparison in each eval")
    .option("--run-self-test", "Run each declared deterministic self-test")
    .option("--trace-boundary", "Emit per-case execution-boundary diagnostics")
    .option("--json", "Output the final batch manifest as JSON")
    .action(
      async (
        skillsRoot: string,
        opts: {
          provider?: string;
          models?: string;
          judgeProvider?: string;
          judgeModel?: string;
          samples?: number;
          db: string;
          outputDir?: string;
          batchId?: string;
          writeSpecs?: boolean;
          failFast?: boolean;
          trigger?: boolean;
          functional?: boolean;
          baselineCheck?: boolean;
          runSelfTest?: boolean;
          traceBoundary?: boolean;
          json?: boolean;
        },
      ) => {
        try {
          const result = await runEvalBatch({
            skillsRoot,
            provider: opts.provider,
            models: opts.models,
            judgeProvider: opts.judgeProvider,
            judgeModel: opts.judgeModel,
            samples: opts.samples,
            db: opts.db,
            outputDir: opts.outputDir,
            batchId: opts.batchId,
            writeSpecs: opts.writeSpecs,
            continueOnError: !opts.failFast,
            trigger: opts.trigger,
            functional: opts.functional,
            baselineCheck: opts.baselineCheck,
            runSelfTest: opts.runSelfTest,
            traceBoundary: opts.traceBoundary,
          });
          printManifest(result, opts.json);
          if (result.manifest.summary.failed > 0) process.exitCode = 1;
        } catch (error) {
          console.error(`Error: ${error instanceof Error ? error.message : String(error)}`);
          process.exitCode = 1;
        }
      },
    );
}
