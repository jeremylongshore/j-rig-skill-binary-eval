import { afterEach, describe, expect, it } from "vitest";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { stringify } from "yaml";
import { buildBaselineSpec } from "./scaffold-spec.js";
import { runEvalBatch, type EvalInvoker } from "./eval-batch.js";

const tempDirs: string[] = [];

afterEach(() => {
  for (const directory of tempDirs.splice(0)) rmSync(directory, { recursive: true, force: true });
});

function skill(root: string, name: string, withSpec = false): string {
  const directory = join(root, name);
  const description = `Helps with ${name} work.`;
  mkdirSync(directory, { recursive: true });
  writeFileSync(
    join(directory, "SKILL.md"),
    `---\nname: ${name}\ndescription: ${description}\n---\n\n# ${name}\n`,
  );
  if (withSpec) {
    writeFileSync(
      join(directory, "eval-spec.yaml"),
      stringify(buildBaselineSpec(name, description)),
    );
  }
  return directory;
}

describe("j-rig eval-batch", () => {
  it("discovers skills deterministically, scaffolds missing specs, and forwards batch lineage", async () => {
    const root = mkdtempSync(join(tmpdir(), "jrig-eval-batch-"));
    tempDirs.push(root);
    skill(root, "alpha-skill", true);
    skill(root, "beta-skill");
    const outputDir = join(root, "batch-output");
    const calls: Array<{ args: string[]; batchId?: string; relativePath?: string }> = [];

    const invokeEval: EvalInvoker = async (args, options) => {
      calls.push({
        args,
        batchId: options.env.JRIG_BATCH_ID,
        relativePath: options.env.JRIG_BATCH_SKILL_RELATIVE_PATH,
      });
      const bundlePath = args[args.indexOf("--emit-bundle") + 1];
      if (!bundlePath) throw new Error("test invoker did not receive bundle path");
      writeFileSync(bundlePath, "[]\n");
      return {
        exitCode: 0,
        signal: null,
        stdout: JSON.stringify({
          sonnet: { provider: "stub", ground_truth: false, decision: "ship" },
        }),
        stderr: "",
      };
    };

    const result = await runEvalBatch({
      skillsRoot: root,
      provider: "deepseek",
      models: "model-a,model-b",
      db: join(root, "evidence.db"),
      outputDir,
      batchId: "batch-test",
      invokeEval,
    });

    expect(result.manifest.schema).toBe("j-rig/eval-batch/v1");
    expect(result.manifest.summary).toEqual({ discovered: 2, completed: 2, failed: 0 });
    expect(result.manifest.entries.map((entry) => entry.skill_relative_path)).toEqual([
      "alpha-skill",
      "beta-skill",
    ]);
    expect(result.manifest.entries.map((entry) => entry.spec_source)).toEqual([
      "existing",
      "generated",
    ]);
    expect(existsSync(result.manifest.entries[1]!.spec_path)).toBe(true);
    expect(readFileSync(result.manifest.entries[1]!.spec_path, "utf8")).toContain(
      "Generated by j-rig eval-batch",
    );
    expect(calls).toHaveLength(2);
    expect(calls[0]!.args).toContain("deepseek");
    expect(calls[0]!.args).toContain("model-a,model-b");
    expect(calls.every((call) => call.batchId === "batch-test")).toBe(true);
    expect(calls.map((call) => call.relativePath)).toEqual(["alpha-skill", "beta-skill"]);
    expect(JSON.parse(readFileSync(result.manifestPath, "utf8"))).toMatchObject({
      schema: "j-rig/eval-batch/v1",
      batch_id: "batch-test",
    });
  });

  it("retains one failed skill and continues the batch by default", async () => {
    const root = mkdtempSync(join(tmpdir(), "jrig-eval-batch-failure-"));
    tempDirs.push(root);
    skill(root, "good-skill");
    skill(root, "bad-skill");

    const invokeEval: EvalInvoker = async (args) => {
      const failed = args.includes(join(root, "bad-skill"));
      if (!failed) {
        const bundlePath = args[args.indexOf("--emit-bundle") + 1];
        if (!bundlePath) throw new Error("test invoker did not receive bundle path");
        writeFileSync(bundlePath, "[]\n");
      }
      return {
        exitCode: failed ? 1 : 0,
        signal: null,
        stdout: "{}",
        stderr: failed ? "provider failed" : "",
      };
    };

    const result = await runEvalBatch({
      skillsRoot: root,
      db: join(root, "evidence.db"),
      outputDir: join(root, "batch-output"),
      batchId: "batch-failure-test",
      invokeEval,
    });

    expect(result.manifest.summary).toEqual({ discovered: 2, completed: 1, failed: 1 });
    const failed = result.manifest.entries.find(
      (entry) => entry.skill_relative_path === "bad-skill",
    );
    expect(failed?.error).toBe("provider failed");
    expect(failed?.status).toBe("failed");
  });
});
